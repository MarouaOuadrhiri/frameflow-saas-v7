function getPath(obj, path) {
  return path.split('.').reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), obj);
}

export function translate(lang, key, vars) {
  let s = getPath(dict[lang], key);
  if (s === undefined) s = getPath(dict.en, key);
  if (s === undefined) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = String(s).split(`{${k}}`).join(v);
  }
  return s;
}

const LangCtx = createContext({ lang: 'en', setLang: () => {}, t: (k, v) => translate('en', k, v) });

export function applyTheme(theme) {
  if (typeof document !== 'undefined') {
    document.documentElement.dataset.theme = theme === 'light' ? 'light' : 'dark';
    try {
      localStorage.setItem('ff_theme', theme);
    } catch {}
    window.dispatchEvent(new CustomEvent('ff:theme', { detail: theme }));
  }
}

export function getSavedTheme() {
  try {
    return localStorage.getItem('ff_theme') || 'dark';
  } catch {
    return 'dark';
  }
}

// Shared theme state hook: Sidebar and Settings stay in sync.
export function useTheme() {
  const [theme, setThemeState] = useState('dark');
  useEffect(() => {
    setThemeState(getSavedTheme());
    const onChange = (e) => setThemeState(e.detail);
    window.addEventListener('ff:theme', onChange);
    return () => window.removeEventListener('ff:theme', onChange);
  }, []);
  const setTheme = (next) => {
    setThemeState(next);
    applyTheme(next);
  };
  return { theme, setTheme };
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState('en');

  useEffect(() => {
    try {
      const saved = localStorage.getItem('ff_lang');
      if (saved === 'ar' || saved === 'fr' || saved === 'en') setLangState(saved);
    } catch {}
    applyTheme(getSavedTheme());
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    try {
      localStorage.setItem('ff_lang', lang);
    } catch {}
  }, [lang]);

  return (
    <LangCtx.Provider value={{ lang, setLang: setLangState, t: (k, v) => translate(lang, k, v) }}>
      {children}
    </LangCtx.Provider>
  );
}

export const useLang = () => useContext(LangCtx);
